/*
A Lewis structure is a chemical representation that describes the arrangement of valence
electrons within a chemical structure.

Lewis structures are commonly used to represent information such as chemical bonding,
lone-pair electrons, and the electron arrangement associated with the atoms of a structure.

Inside the Compound Handbook, the Structure Generation system can generate a
LewisStructureModel that represents the generated Lewis structure before that result
is ultimately used or presented by other parts of the program.

However, generating a LewisStructureModel does not automatically guarantee that the
generated structure satisfies the validation requirements expected by the Compound Handbook.

The generated Lewis structure should therefore be validated before the program relies upon
it as an acceptable structure representation.

This is why, ILewisStructureValidator interface is being created to define the contract
for validating a LewisStructureModel.

The validator receives a LewisStructureModel object and returns a ValidationResult.

The returned ValidationResult can indicate whether the generated Lewis structure is
considered valid and can also contain the collection of ValidationIssue objects discovered
while validating that structure.

The interface only defines what a Lewis-structure validator must be able to do.
It does not define the particular Lewis-structure validation rules or the implementation
used to perform those checks.
*/

/*
The following ILewisStructureValidator is an interface.

An interface defines a contract that specifies which functionality an implementing class
must provide without specifying how that functionality must be implemented.

I am using an interface here because the rest of the Compound Handbook should be able to
request validation of a generated LewisStructureModel without depending directly upon
one particular validator implementation.

This also keeps Lewis-structure generation and Lewis-structure validation as separate
responsibilities.

The Structure Generation system can be responsible for constructing the Lewis structure,
while the Validation system can independently determine whether that generated structure
satisfies the required validation rules.

Any class that implements ILewisStructureValidator must provide the Validate() method
defined by this interface.
*/

using CompoundHandbook.StructureGeneration;

namespace CompoundHandbook.Validation 
{
    /* 
    The following interface defines the contract for validating a LewisStructureModel
    generated by the Structure Generation system.
    */
    public interface ILewisStructureValidator 
    {
        /*
        The following Validate() method receives a LewisStructureModel object and checks it
        according to the Lewis-structure validation rules provided by the class that
        implements this interface.
        
        LewisStructureModel is the datatype of the parameter.
        model is the name of the parameter.
        Therefore, the model parameter represents the generated LewisStructureModel that needs to be validated.
        Passing the LewisStructureModel itself allows the validator to inspect the information contained within 
        the generated Lewis-structure representation.
        
        ValidationResult is the return type of this method.
        This means that after the LewisStructureModel has been validated, the method returns a ValidationResult object.

        That ValidationResult can contain:
        (i)  IsValid : The overall Boolean validation state.
        (ii) Issues  : The collection of ValidationIssue objects discovered during validation.

        Since this is an interface method, there is no method body here.

        The actual Lewis-structure validation logic will be supplied by a class that
        implements ILewisStructureValidator.
        */
        ValidationResult Validate(LewisStructureModel model);
    }
}